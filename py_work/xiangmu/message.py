#    - 物理真相：底层是去对象的 __dict__ 字典里找对应的 Key。
#    - 极客警告：编译期不报错，如果属性名拼错，会在运行期当场触发 AttributeError 闪退。
# 
# 3. 组合优于继承（Composition over Inheritance）：
#    - 继承（子类）：强耦合。底层是结构体的死嵌套，父类改动会导致所有子类重排内存。
#    - 组合（传 self）：弱耦合。底层是结构体里放个指针，随插随用。
#    - 极客法则：能“借用”（传 self）就不要“认干爹”（继承），除非需要利用多态重写方法。
#
# 4. 💻 C语言视角完美映射：
#    - Python 的传 self 相当于 C 的 void* 强转传参。
#    - 只要传进来的 void* 指向的结构体，在特定偏移量上刚好是所需的成员，就能跑。
