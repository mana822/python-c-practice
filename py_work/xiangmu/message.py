#    - sys 模块（后门）：System 的缩写。它是解释器直接暴露给操作系统的接口，
#      是你在沙盒里找到的“物理面板”。
#
# 2. 底层物理真相（sys 到底干了啥？）：
#    - sys 底层是纯正的 C 语言代码（CPython 核心）。一旦调用，直接绕过沙盒的
#      虚拟保护，和操作系统的内核对话。
#    - 典型例子：sys.exit() 物理动作相当于 C 语言的 exit(0)。它直接向操作系统
#      发送终止信号，物理击毙进程，释放所有内存（不走异常抛出机制）。
#
# 3. 极客实战映射（外星人游戏为例）：
#    - pygame.QUIT 捕获玩家点 X。
#    - sys.exit() 直接关闭整个进程，防止僵尸进程卡死操作系统。
#    - 如果不用 sys，只用 break，底层的 pygame 窗口和硬件句柄可能释放不干净。
# 
# 4. 其他后门黑科技（C 语言视角）：
#    - sys.argv：相当于 C 的 main(int argc, char** argv)，拿命令行参数。
#    - sys.path：底层找包的物理路径列表。
#    - sys.stdout：相当于 C 的 FILE* stdout。
#
# 5. [极客箴言]：
#    - Python 语法是拿来“做开发”的（安全隔离）。
#    - sys/os 模块是拿来“搞事情”的（与内核底层对话）。
#    - 真极客，懂得在沙盒里写业务，在 sys 里定生死。
