# ============================================================================
# 【极简笔记：类的“第三空间”与 self/类名 调用的物理真相】
# ============================================================================
#
# 1. 逻辑本质（三大作用域的物理隔离）：
#    - 局部作用域（Local）：函数/方法内部的临时变量（在栈帧里，用完即毁）。
#    - 全局作用域（Global）：模块最外层的变量（在全局数据区，整个文件可见）。
#    - 类命名空间（Class）：定义在 class 内部的属性和方法。它们被独立打包成了
#      一个类字典（__dict__）。【既不在全局，也不在局部】。
#
# 2. 底层物理真相（为什么裸写方法名会报错）：
#    - Python 寻找变量/方法的默认路线：Local -> Global -> Built-in。
#    - 这条路线【绝对不会】自动去类字典里搜。
#    - 所以，如果在方法 A 里直接写 method_B()，Python 全局找不到，当场报 NameError。
#
# 3. 破局方案（两把钥匙）：
#    - 方案一：用 self。self 是实例指针，底层顺着 self 找到 __class__，再进类字典拿
#      出方法（底层会自动把 self 隐式传进去）。
#    - 方案二：用 类名（如 Player.method_B）。直接用类名去类字典里强拿方法。
#      🚨 致命警告：用类名调用时，它是“未绑定的（Unbound）”，你必须手动把实例
#      传进去（如 Player.method_B(my_player)），否则会报参数缺失错误。
#
# 4. 💻 极客跨界视角（C 语言完美映射）：
#    - class Player: 相当于 struct Player。
#    - def method(self): 相当于把函数指针塞进 struct。
#    - self.method() 相当于 self->method()。
#    - Player.method(self) 相当于手动调用 Player_method(self)。
#
# 5. [极客箴言]：
#    - 类是一个独立的保险柜，不是大马路。
#    - 拿保险柜里的东西，要么用钥匙（实例 self），要么用起重机（类名）。
# ============================================================================

