# 【极简笔记：Surface 与 Rect 的物理关系与数据获取】
# ============================================================================
#
# 1. 物理本质：
#    - Surface（肉身）：存储像素数据的内存块。它自带头部信息（width, height）。
#    - Rect（骨架）：隐形的矩形框。只包含四个整数（x, y, w, h），没有像素数据。
#
# 2. 核心物理法则：
#    - Surface 决定“长什么样”，Rect 决定“在哪（坐标）”和“多大（边界）”。
#    - 移动、碰撞检测全在 Rect 层面完成；图像渲染（blit）需要 Surface + Rect 配合。
#
# 3. 如何从 Surface 获取大小？
#    - size = surface.get_size()    # 返回 (宽, 高) 元组
#    - w = surface.get_width()      # 读取宽度
#    - h = surface.get_height()     # 读取高度
#
# 4. 极客最爱：surface.get_rect()
#    - 底层动作：读取 Surface 的宽高，在内存中 malloc 一个 Rect 对象。
#    - 默认状态：x=0, y=0, w=图片宽, h=图片高。
#    - 用法：通过改变 rect.x / rect.y / rect.center 等属性，实现图像定位。
#
# 5. 💻 C语言视角：
#    struct Surface { int w, h; char* pixels; };
#    struct Rect { int x, y, w, h; };
#    get_rect() 相当于读取 Surface 的 w, h 并赋值给 Rect 的 w, h。
# ============================================================================


