#include <stdio.h>
#define N 10
void quicksort(int a[], int low, int high);
int split(int a[], int low, int high);

int main(void)
{
    int a[N], i;
    printf("Enter %d numbers to be sorted: ", N);
    for (i = 0; i < N; i++)
        scanf("%d", &a[i]);
    quicksort(a, 0, N - 1);
    printf("In sorted order: ");
    for (i = 0; i < N; i++)
        printf("%d ", a[i]);
    printf("\n");
    return 0;
}
// 因为函数传数组是直接拿绝对地址直接改变，所以不要返回，直接改就行了
void quicksort(int a[], int low, int high)
{
    int middle;
    if (low >= high) return;       // <-- 这里面的low和high就是递归里面给的元素啊，相撞就停止(递归函数总有个判断终点的，判断条件可能是内部的值，可能是传递形参的值)
    middle = split(a, low, high);   // 返回分割元素的位置
    quicksort(a, low, middle - 1);   // 继续排列分隔元素前面的数
    quicksort(a, middle + 1, high);   // 排列分隔元素后面的
}
// 这里逻辑是，用第一个元素做分隔元素，开始选high处，选到往左填，之后选low，选到往右填，直到相撞，但是要记得随时随地判断
int split(int a[], int low, int high)
{
    int part_element = a[low];    // <-- 选第一个为分割元素

    for(;;) {           // 换成while (low < while) 也可以，但也要用内部结束，因为内部是多次循环，且中途会改变值
        // 这里用小于，而不能等于，因为等于都相撞了，已经不要选了，是留给分隔元素的，你要知道，不管是low的对比，还是high的对比，都是选数去对方，对方是“空的”，当选的时候和空的位置想装了，“没有值了”
        // 最关键的是，下面有个自减，你就一定不能等于了，不然后面自减连不起来，还要做判断,如果相撞了，这个值要留着，而不是自减
        while (low < high && part_element <= a[high])  // <-- 用分割元素排high处的数，只要大就跳过，high往前跳转，直到遇到小的
            high--;   // 每次改变后都要判断
        if (low >= high) break;
        a[low++] = a[high];    // <-- 把high处小的补给最左边的，然后low往右偏移下，high不动是因为给它留着位置让low去占，都是同理，比low说明high“空着”，反之

        while (low < high && a[low] <= part_element) // <-- 检测low这边是否比分割元素小(因为这时右边的坑空了一个，所以想办法把左边元素看能不能移过去)
            low++;          // <-- 成功一次，往右继续检索
        if (low >= high) break;
        a[high--] = a[low];      // <-- 这时候遇到大的了，就填坑过去(往复循环，直到相撞)

    }
    a[high] = part_element;      // 之后把分割元素填进去
    return high;              // 返回分割元素位置，好去左右继续排列
}
// 注意，这里都是下标去算，空也不是真的空了，我们当成空了，覆盖过去


/* ============================================================================
 * 【极客终极复盘：快排递归与栈帧博弈】
 * ============================================================================
 *
 * 一、 递归四问：
 *    - 停止条件：low >= high，区间枯竭，栈分支刹车。
 *    - 递归条件：分割得到 middle，分别向左右小区间逼近。
 *    - 改变了什么：split 在局部下标来回移动；递归生成全新子区间。
 *    - 返回了什么：返回基准落点，用来切出新任务；不是直接返回排序结果。
 *
 * 二、 两层递归形态：
 *    - 【split：一趟分区】：局部下标碰撞，定基准归宿；属于单次任务。
 *    - 【quicksort：分治递归】：非尾递归；下层处理完再继续另一分支，栈帧保留。
 *
 * 三、 C 使用现实约束：
 *    - 如果数组接近有序，固定选左基准会退化，递归深度爆炸、容易爆栈。
 *    - 递归调用有压栈开销；大量数据场景迭代更稳。
 *    - 挖坑法依靠逻辑覆盖，不存在真实空洞；区分 split 内部碰撞 和递归终止。
 *
 * 四、 [极客箴言]：
 *    - split 负责“一刀定乾坤”；递归负责不断啃碎剩下的区间。
 *    - 递归终止不是指针撞在一起，是区间耗尽；相撞发生在另一函数里。
 *    - 看懂任务如何裂变，就能分清“翻译公式递归”和“分治递归”。
 * ============================================================================
 */
