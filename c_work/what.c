/* ============================================================================
 * 【极客终极复盘：递归中的局部静态变量 —— 全是约定，全是编译器干的，CPU 什么都不知道】
 * ============================================================================
 *
 * 0. 一句话总纲
 *
 *    作用域、遮蔽、静态存储期、自动存储期、递归共享还是每层独立——
 *    全都是 C/C++ 语言标准的人为约定。
 *    编译器按这些约定做名字解析、分配存储、生成指令。
 *    CPU 只认地址和指令，它不知道什么叫块、作用域、static、遮蔽、递归层。
 *
 * ============================================================================
 * 1. 修正原句（原句混了三个维度）
 *
 *    ❌ 原句：
 *      “具有静态存储期的局部变量，当函数是递归函数时，每次调用它(用实参传递)
 *       都会产生其自动变量的新副本。静态变量就不会发生这种情况，相反，所有的
 *       函数调用都共享一个静态变量(除非发生变量遮蔽，就用自己的，不改变外面的)”
 *
 *    ✅ 修正：
 *      “局部自动变量在每次函数调用（包括递归每一层）时，都会在当前栈帧中创建
 *       新副本；局部静态变量不会随调用创建新副本，它整个程序运行期只存在一份，
 *       所有调用（包括所有递归层）共享同一个对象。若在代码文本的内层块中又声明
 *       同名 static，那是另一个静态对象，内层遮蔽外层，两个对象各自全程序一份，
 *       互不影响。递归本身不产生新的词法作用域，也不会造成遮蔽。
 *       以上全部是语言约定，由编译器按约定实现；CPU 只执行地址访问，不参与判断。”
 *
 *    错在哪：
 *    - 把 static 和 auto 混了；
 *    - “用实参传递”跟静态变量共享无关；
 *    - 遮蔽是编译期词法概念，不是运行时开关。
 *
 * ============================================================================
 * 2. 约定表：语言规定什么，编译器就干什么
 *
 *    | 语言约定（标准规定）              | 编译器按约定干什么                     | CPU 知道吗 |
 *    |-----------------------------------|----------------------------------------|------------|
 *    | `{}` 形成块作用域                 | 建作用域栈，做名字解析                 | 不知道     |
 *    | 内层同名声明遮蔽外层              | 把内层名字解析到内层声明               | 不知道     |
 *    | 自动变量：块作用域+自动存储期     | 分配在栈帧，生成“栈帧+偏移”寻址        | 不知道     |
 *    | 局部 static：块作用域+静态存储期  | 分配固定符号/地址，生成固定地址寻址    | 不知道     |
 *    | 同一作用域同名重复定义 → 报错     | 编译期直接报错，不生成代码             | 不知道     |
 *    | 局部 static 只初始化一次          | 生成隐藏 guard 或加载时初始化          | 不知道     |
 *    | 递归是同一函数的多次调用          | 每次调用生成压栈帧代码，代码只有一份   | 不知道     |
 *
 *    结论：约定是标准定的；执行约定是编译器干的；CPU 只按生成的地址指令跑。
 *
 * ============================================================================
 * 3. 两个正交维度（也是约定拆开的）
 *
 *    【词法作用域】编译期：名字在哪可见、解析到哪个声明、谁遮蔽谁。
 *    【存储期】    编译期：对象放哪、活多久、有几份。
 *    【栈帧】      运行期：每次调用一个，自动变量住在里面。
 *    【递归】      运行期：同一段代码多次调用，只压新栈帧。
 *
 *    递归只动栈帧。不产生新代码文本 → 不产生新作用域；
 *    不改变存储期 → 不改变静态变量“全程序一份”。
 *
 *    // 案发现场 0：谁住哪，全是编译器按约定安排的
 *    void f(int n) {
 *        int a = n;         // 约定：自动存储期 → 编译器放栈帧 → 每层一份
 *        static int s = 0;  // 约定：静态存储期 → 编译器放静态区 → 全程序一份
 *        if (n > 0) f(n - 1);
 *    }
 *
 * ============================================================================
 * 4. 递归运行时到底发生什么（编译器生成的代码在跑）
 *
 *    - 函数机器码只有一份，不是复制出 f1、f2、f3；
 *    - 每次调用压新栈帧：参数、返回地址、自动变量；
 *    - 当前帧调子函数时暂停但不销毁，子调用返回后按返回地址继续；
 *    - 自动变量：每层栈帧各一份，地址通常不同；
 *    - 局部 static：不在栈帧里，编译期绑定固定符号/地址，所有层访问同一个。
 *
 *    // 案发现场 1：自动变量每层独立，静态变量全层共享
 *    void f(int n) {
 *        int a = n;
 *        static int s = 0;
 *        s++;
 *        if (n > 0) f(n - 1);
 *        printf("n=%d a=%d s=%d\n", n, a, s);
 *    }
 *    f(2);
 *    // 输出（弹栈顺序）：
 *    // n=0 a=0 s=3
 *    // n=1 a=1 s=3
 *    // n=2 a=2 s=3
 *    // a 三个不同对象；s 同一个对象，值累加到 3。
 *
 *    注意：这是编译器按“自动变量放栈帧、静态变量放固定地址”的约定生成的代码
 *    跑出来的结果。CPU 只是执行地址读写，它不知道哪个是 a、哪个是 s。
 *
 * ============================================================================
 * 5. 静态局部变量“圈哪块地”：编译期绑符号，运行期不圈地
 *
 *    - 块作用域不是运行时领地，是编译期名字解析范围（约定）；
 *    - static 声明被编译器绑定到固定存储符号；
 *    - 访问点编译成“访问该固定地址”，栈帧怎么变都不影响；
 *    - 不是“执行到这块，编译器现场开 static”，是编译期早就开好了。
 *
 *    // 案发现场 2：编译期符号绑定（概念示意）
 *    void f(int n) {
 *        static int s = 0;   // 编译器：分配符号 S，固定地址
 *        if (n > 0) f(n - 1);
 *    }
 *    // 每层递归执行同一段机器码，访问的都是符号 S 的地址。
 *
 *    编译器内部记账：作用域栈 + 符号表，用来解析名字。
 *    目标文件符号表：局部 static 变成 local 符号（如 f.s），给链接器填地址。
 *    运行时：符号名早没了，指令里只有地址/偏移。CPU 不知道有“符号”这回事。
 *
 * ============================================================================
 * 6. 初始化：只发生一次，也是编译器按约定生成的
 *
 *    - 静态存储期变量先零初始化；
 *    - 带初值的动态初始化只在第一次执行到声明时做一次；
 *    - C++11 起局部 static 初始化线程安全（隐藏 guard）；
 *    - 后续所有递归层、所有调用都不再初始化。
 *
 *    // 案发现场 3：先递归、后声明，最深层先触发初始化
 *    void f(int n) {
 *        if (n > 0) f(n - 1);   // 这里看不到 s
 *        static int s = 0;      // 第一次执行到这里才初始化
 *        s++;
 *        printf("n=%d s=%d\n", n, s);
 *    }
 *    f(2);
 *    // n=0 s=1
 *    // n=1 s=2
 *    // n=2 s=3
 *    // 初始化只一次；但每层必须执行到声明之后才能按名字访问。
 *    // guard 也是静态区固定地址，编译器生成检查代码；CPU 只执行比较和跳转。
 *
 * ============================================================================
 * 7. 遮蔽法则：看花括号，不看递归层（编译器按约定解析名字）
 *
 *    - 同一作用域同名声明 → 约定为重定义，编译错误；
 *    - 内层块同名声明 → 约定为合法遮蔽，两个不同对象；
 *    - 递归不产生新词法作用域，所以不会“因为递归了”就多一层遮蔽；
 *    - 内层 static 也是全程序一份，所有递归层共享“内层那个对象”。
 *
 *    // 案发现场 4：同一作用域同名 → 编译错误
 *    void f(int n) {
 *        static int x = 0;
 *        static int x = 1;  // ❌ 重定义，编译器直接报错
 *    }
 *
 *    // 案发现场 5：内层块同名 → 合法遮蔽，两个 static 各自一份
 *    void f(int n) {
 *        static int x = 0;      // A：函数体块作用域
 *        if (n > 0) f(n - 1);   // 这里只能看到 A
 *        {
 *            static int x = 1;  // B：内层块作用域，遮蔽 A
 *            // 这里访问 B；B 也是全程序一份，所有递归层共享 B
 *        }
 *        // 出了块，又只能看到 A
 *    }
 *    // 不是“外层递归看 A、内层递归看 B”；
 *    // 是每次调用都在块外看 A、进块内看 B。递归层 ≠ 词法块。
 *    // 编译器给 A、B 分配两个不同符号，指令里直接编码各自地址。
 *
 * ============================================================================
 * 8. 常见误解速杀（都是把约定当成物理事实或把运行期当编译期）
 *
 *    ❌ “递归是多个独立小世界，所以 static 应该每层一份”
 *       → 递归是同一函数的多次调用，不是多个函数；static 不在栈帧里。
 *
 *    ❌ “递归嵌套了，作用域也嵌套了”
 *       → 运行期调用嵌套 ≠ 编译期词法嵌套；编译器只认代码文本的大括号。
 *
 *    ❌ “静态变量能延续，是因为递归有规律，编译器按规律圈地”
 *       → 静态存储期约定为全程序一份；递归规不规律都一样。编译器按声明绑符号。
 *
 *    ❌ “遮蔽就是暂时用自己的，不改变外面的”
 *       → 内层同名 static 是另一个对象，它自己也只有一份；两个对象互不影响。
 *
 *    ❌ “每次执行到块，就新开一个静态变量”
 *       → 静态变量不新开；新开的是栈帧里的自动变量。static 编译期固定地址。
 *
 *    ❌ “CPU 看到作用域标记才知道怎么访问”
 *       → 运行时没有作用域标记。编译器编译期完成名字解析，指令里只有地址/偏移。
 *
 *    ❌ “编译器不讲逻辑，乱规定”
 *       → 编译器严格按语言标准约定翻译；约定是人为的，但执行是有严格逻辑的。
 *
 * ============================================================================
 * 9. 💻 编译/链接/运行三层映射（谁干了什么）
 *
 *    编译器（编译期）：
 *      - 建作用域栈、符号表，做名字解析；
 *      - int a;              → 生成“当前栈帧 + 偏移”的访问代码；
 *      - static int s = 0;   → 在静态区分配符号 S，访问代码直接引用 S；
 *      - 内层 static int x;  → 另一个符号 X2，块内解析到 X2，块外解析到 X1；
 *      - 同一作用域同名 → 直接报错；
 *      - 作用域信息用完即弃（调试信息除外）。
 *
 *    链接器（链接期）：
 *      - 把局部 static 的 local 符号放进最终地址空间；
 *      - 不跨文件匹配 local 符号；
 *      - 把代码里的符号引用填成最终地址/偏移。
 *
 *    运行期（CPU）：
 *      - 每次调用 f → 压新栈帧 → 自动变量在栈帧偏移处 → 每层独立；
 *      - 所有调用访问 static → 同一个固定地址 → 共享、累加、只初始化一次；
 *      - CPU 只认地址和指令，不知道作用域、遮蔽、static、递归层。
 *
 * ============================================================================
 * 10. [极客箴言]
 *
 *    - 作用域、遮蔽、存储期、递归共享，全是语言约定；编译器按约定翻译，CPU 只认地址。
 *    - 递归不是复制函数，是复制栈帧；函数代码和静态对象都只有一份。
 *    - 自动变量跟栈帧走，静态变量跟声明走；作用域管名字，存储期管对象。
 *    - 静态变量不“知道”递归到哪层，它只知道编译器给它绑的固定地址。
 *    - 遮蔽看花括号，不看递归深度；同层同名必死，内层同名才是另一个对象。
 *    - 共享不是递归的恩赐，是静态存储期的约定；独立不是递归的例外，是栈帧的常态。
 *    - 编译器内部有作用域栈和符号表，目标文件有 local 符号，运行时只有地址。
 *    - 约定就是约定，编译器按约定干活，CPU 什么都不知道。
 * ============================================================================
 */


