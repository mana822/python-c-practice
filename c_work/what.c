/* ============================================================================
 * 【极客终极复盘：冯·诺依曼架构的物理现场 —— 各司其职与 VLA 灾难】
 * ============================================================================
 * 
 * 1. 核心分工：四大地缘板块的物理职责
 *    - .text（代码段）：只读图纸。里面只有机器指令（MOV/JMP等），没有变量名。
 *      指令中硬编码了局部变量的“相对偏移量”。
 *    - .data / .bss（数据段）：全局仓库。存放全局/静态变量。链接器直接分配好
 *      “绝对物理地址”，程序启动即存在，直到结束。
 *    - Stack（栈区）：临时工作台。存放局部变量。从高地址向低地址生长（倒着长）。
 *    - CPU（执行者）：盲目的算力机器。不认变量名，只认地址。依靠 RBP/RSP 寄存器
 *      和指令里的偏移量，算绝对地址（Address = RBP - Offset）。
 * 
 * 2. 核心联动：栈帧布局（从高地址 -> 低地址）
 *    - [参数区]：x86-64下前6个参数走寄存器，第7个起从右向左压栈。
 *    - [Return Address]：回城卷轴。执行 call 时 CPU 自动压入，存 .text 中的代码地址。
 *      决定函数结束后跳回哪里（黑客栈溢出首选目标）。
 *    - [Saved RBP]：旧地契。执行 push rbp 时压入，存父函数的栈底坐标。
 *      保护现场，等当前函数 ret 时，用来恢复 RBP 寄存器。
 *    - [局部变量区]：执行 sub rsp, X 划出。按类型大小和对齐规则排布。
 * 
 * 3. 认知碰撞：相对寻址 vs 绝对寻址
 *    - 局部变量：靠 [RBP - X] 相对寻址。不同函数偏移量可复用，因为 RBP 基准在变。
 *    - 全局变量：靠写死的绝对地址（或相对程序基址）寻址，全局唯一。
 *    - 内存复用：栈空间的地址会被不断覆盖（时间维度上的复用），死人给活人腾地。
 * 
 * 4. 致命特例：变长数组（VLA）的物理灾难
 *    - 固定数组：函数刚进门，机器码立刻执行 sub rsp, 常量。地皮一次性圈好，
 *      代码里怎么 goto 都不会死。
 *    - VLA 数组：大小依赖运行期变量。编译器将 sub rsp, 变量 的指令混入业务代码中。
 *    - 灾难一（goto越界）：若用 goto 跳过 VLA 声明，就跳过了分配指令，但编译器
 *      在函数末尾的栈恢复逻辑（记账）已写死，直接导致栈帧撕裂（Undefined Behavior）。
 *    - 灾难二（动态寻址）：VLA 没有固定的死偏移量，编译器必须在栈上额外藏一个
 *      指针，每次访问都要“先读指针，再顺着指针找地址”，极度拖慢性能。
 * 
 * 5. [极客箴言]
 *    - 变量名是编译期的谎言，物理世界里只有偏移量与绝对地址。
 *    - .text 只是图纸，没有数据。一切数据都在 .data 和 Stack 中等待被 CPU 搬砖。
 *    - VLA 打破了“进门一次性圈地”的铁律，把空间分配变成了时间流水线，
 *      是底层性能与安全的双重毒药，工业界坚决封杀。
 * 
 * 6. [验证命令]
 *    - 查看汇编：gcc -S test.c 观察 sub rsp 的位置（固定 vs 动态）。
 *    - 打印地址：printf("%p", &a); 观察每次函数调用时局部变量的绝对地址变化。
 * ============================================================================
 */

 

