// ============================================================
// 第8章 第17题：生成 n×n 幻方（n 为奇数，1~99）
// 题目：
//   1 放在第 0 行中间，后续数依次向上移动一行并向右移动一列，
//   越界绕回；如果目标位置被占用，放在前一个数的正下方。
// ============================================================

// * 你的代码（保留原样，在原处标注）：
#include <stdio.h>

int main(void)
{
    printf("This program creates a magic square of a specified size.\n");
    printf("The size must be an odd number between 1 and 99.\n");
    printf("Enter size of magic square: ");
    int n;
    scanf("%d", &n);

    // ⚠️ 警告：没有验证 n 是 1~99 的奇数。
    // 题目说“The size must be an odd number between 1 and 99”，
    // 用户输入偶数、0、负数或超过 99 时，程序行为不符合要求。
    // 严谨写法应在使用前加：
    //   if (n < 1 || n > 99 || n % 2 == 0) {
    //       printf("Size must be an odd number between 1 and 99.\n");
    //       return 1;
    //   }

    int list[n][n];   // * VLA（变长数组），C99 起支持。
                      // * 题目也提到“如果编译器支持变长数组，声明 n 行 n 列”，
                      //   你的选择符合题意。

    for (int i = 0; i < n; i++)
        for (int j = 0; j < n; j++) {
            list[i][j] = 0;
        }

    int a, b;
    a = 0, b = (n - 1) / 2;
    list[a][b] = 1;   // ✅ 1 放在第 0 行中间，正确。

    int q1, q2;
    int i = 2;
    for (; i <= n * n; i++) {
        q1 = a, q2 = b;   // * 记录上一个位置，正确。

        // ✅ 修改 1、2：先算右上，再统一绕回，结构清晰，正确。
        a = a - 1;
        b = b + 1;

        if (a < 0) a = n - 1;   // ✅ 向上越界，绕回最后一行。
        if (b >= n) b = 0;      // ✅ 向右越界，绕回第一列。

        // ✅ 修改 3：碰撞检测，回滚到正下方。
        // * 你的注释“题意是正下方”，理解正确。
        if (list[a][b] != 0) {
            a = q1 + 1;         // ⚠️ 这里可能越界。
            b = q2;
        }

        // ✅ 修改 4：赋值统一放在最后，正确。
        // * 你注释里说之前版本“分支里写了无数 i++ 导致卡死”，
        //   现在每个 i 只在 for 的第三个表达式里自增一次，没问题。
        list[a][b] = i;
    }

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            printf("%3d", list[i][j]);
        }
        printf("\n");
    }

    return 0;
}

