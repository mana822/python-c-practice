#include <stdio.h>
#include <stdlib.h>
#include <time.h>

int main(void)
{
    int a, b;
    int j = 0, k = 0, m;
    long long s = 0;

    // * GCC 范围指定初始化器，GCC 下合法；
    // * 标准 C 下不合法，跨编译器需改为循环赋 '.'。
    char size[10][10] = {[0 ... 9][0 ... 9] = '.'};

    srand((unsigned) time(NULL));

    for (int i = 1, n = 0; i <= 26;) {
        m = rand() % 4;

        // * 重试次数兜底：最终一定会退出。
        // * 注意：这不是“四方向堵住立即终止”，
        // * 而是“重试到十亿次才放弃”。
        if (s > 1000000000)
            break;

        size[j][k] = 'A' + n;
        a = j;
        b = k;

        switch (m) {
            case 0: j++; break;
            case 1: j--; break;
            case 2: k--; break;
            case 3: k++; break;
        }

        // * 越界或已访问，回退并重试。
        if (j < 0 || j > 9 || k < 0 || k > 9 || size[j][k] != '.') {
            s++;
            j = a;
            k = b;
            continue;
        }

        // * 移动成功，放完当前字母后推进到下一个字母。
        i++;
        n++;
    }

    for (int i = 0; i < 10; i++) {
        for (int n = 0; n < 10; n++) {
            printf("%c ", size[i][n]);
        }
        printf("\n");
    }

    return 0;
}

