#include <stdio.h>

float sum(int);   // ⚠️ 函数名 sum 不恰当：这里算的是税金，不是求和。
                  //    而且函数内局部变量也叫 sum，同名遮蔽，可读性差。
                  //    建议改成 float tax(double income);。

int main(void)
{
    int n;        // ⚠️ 应纳税所得额用 int 会丢掉小数部分。
                  //    第5章第5题原程序用的是 float income，
                  //    这里建议改成 double income;，scanf 用 %lf。

    printf("Enter your money: ");
    scanf("%d", &n);

    // ✅ 你的注释“返回值要去接，返回的变量不是这个函数的变量”
    //    完全正确。函数返回值必须用变量接收或直接使用，
    //    函数内的局部变量在函数返回后就销毁了。
    float m = sum(n);

    printf("%.3f", m);   // ⚠️ 输出没有标签、没有换行。
                         //    题目示例是 "You need pay $..." 之类，
                         //    建议加标签和 \n。
                         //    %.3f 三位小数，题目示例通常是两位，
                         //    但题目没强制，可以保留。

    return 0;
}

float sum(int n)   // ⚠️ 参数类型 int，与 main 里的 int 一致，但建议改 double。
{
    // ❌ 严重可读性问题：局部变量名 sum 与函数名 sum 同名。
    //    合法，但函数内部 sum 指局部变量，遮蔽了函数名。
    //    return sum; 返回的是局部变量，逻辑正确，
    //    但这种同名写法极易看混，强烈建议改名。
    float sum;

    if (n <= 750)
        sum = n * 0.01f;
    else if (n <= 2250)
        sum = 7.50 + (n - 750) * 0.02f;
    else if (n <= 3750)
        sum = 37.50 + (n - 2250) * 0.03f;
    else if (n <= 5250)
        sum = 82.50 + (n - 3750) * 0.04f;
    else if (n <= 7000)
        sum = 142.50 + (n - 5250) * 0.05f;
    else
        sum = 230.00 + (n - 7000) * 0.06f;

    return sum;
}

