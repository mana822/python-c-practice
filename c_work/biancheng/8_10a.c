//   输入 690（11:30）  → 12:47，15:00   ✅
//   输入 1400（23:20） → n=8 修正为 7 → 21:45，23:58  ✅
//
// * 关键点：
//   1. 两个数组：depart 和 arrive，符合题目要求。
//   2. 循环找第一个 >= time 的起飞时间，找到就 break。
//   3. time 超过最后一班时，n 变成 8，修正为 7，选最后一班。
//   4. 输出用 depart[n] / 60 和 depart[n] % 60，
