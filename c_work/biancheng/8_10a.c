// * 批改：
//
// ✅ 搜索逻辑正确：
//    time_fly[n] - time >= 0 即 time_fly[n] >= time，
//    从小到大找第一个 >= 用户时间的航班，就是“能赶上的下一班”。
//    找到后 break，正确。
//
// ❌ 错误 1：缺少抵达时间数组。
//    题目明确要求“另一个数组存储航班抵达时间”，
//    你只声明了起飞时间数组，也没有输出抵达时间。
//
// ❌ 错误 2：用户时间超过 1305 时什么都不输出。
//    如果 time > 1305，循环里所有条件都不成立，
//    循环结束，程序没有任何输出。
//    应处理为：超过最后一班时，选最后一班。
//
// ⚠️ 警告 1：switch 映射太冗长。
//    时间本身已经是分钟数，输出时用除法和取余就能转成时:分，
//    不需要 8 个 case 手写文本，也不涉及指针和字符串数组。
//
// ⚠️ 警告 2：提示语 "Enter your flying time(m): " 不清楚。
//    m 可能被理解成米、月，建议写清楚是“从午夜开始的分钟数”。
//
// ------------------------------------------------------------
// * 修正版（本文件唯一可运行的 main）：
// * 不用指针，不用字符串数组，时间全部用整数存，
// * 输出时用 / 60 和 % 60 转成时:分。
// ------------------------------------------------------------

#include <stdio.h>

int main(void)
{
    int time;
    int n;

    // * 起飞时间，从午夜开始的分钟数。
    int depart[8] = {480, 583, 679, 767, 840, 945, 1140, 1305};

    // * 抵达时间，同样用分钟数。
    int arrive[8] = {616, 712, 811, 900, 968, 1075, 1280, 1318};

    printf("Enter a 24-hour time in minutes: ");
    scanf("%d", &time);

    // * 从 0 到 7 找第一个 >= time 的起飞时间。
    for (n = 0; n < 8; n++) {
        if (depart[n] >= time)
            break;
    }

    // * 如果 time 超过最后一班，n 会变成 8，
    // * 这时选最后一班，下标 7。
    if (n == 8)
        n = 7;

    // * 用除法和取余把分钟数转成 时:分，
    // * %02d 保证分钟不足两位时补零。
    printf("Closest departure time is %d:%02d, arriving at %d:%02d\n",
           depart[n] / 60, depart[n] % 60,
           arrive[n] / 60, arrive[n] % 60);

    return 0;
}

