// * 你的想法：
// if (hand[NUM_CARDS-1][0] - hand[0][0] == 12)
//     加到判断顺子里面（判断为顺子后再去判断这种类型顺子）

// * 批改：
//
// ✅ 边界改对了：hand[NUM_CARDS-1][0] 是 hand[4][0]，不越界。
//
// ❌ 位置理解有误：
//    小 A 顺排序后是 2,3,4,5,14，相邻差是 1,1,1,9，
//    普通 straight 判断要求相邻差 1，所以 straight 会被判成 false。
//    也就是说，小 A 顺本来就不是普通顺子。
//    如果把它写在“判断为顺子之后”的分支里：
//        if (straight) { if (差值 == 12) ... }
//    永远进不去，因为小 A 顺 straight 已经是 false。
//
//    正确位置：普通 straight 判断之后，
//    如果 straight 为 false，再单独检查小 A 顺。
//
// ❌ 差值 12 不够严谨：
//    2,3,4,6,14 首尾差也是 12，但不是顺子。
//    只判断差值 12 会把这种牌误判成小 A 顺。
//
// ------------------------------------------------------------
// * 正确写法 1：逐项精确比较（最稳）
// ------------------------------------------------------------
// 放在普通 straight 判断之后：

for (int i = 1; i < NUM_CARDS; i++) {
    if (hand[i - 1][0] + 1 != hand[i][0])
        straight = false;
}

// * 小 A 顺：排序后必须是 2,3,4,5,14。
if (!straight &&
    hand[0][0] == 2 && hand[1][0] == 3 &&
    hand[2][0] == 4 && hand[3][0] == 5 &&
    hand[4][0] == 14)
{
    straight = true;
}

if (straight)
    return;

// ------------------------------------------------------------
// * 正确写法 2：首尾 + 中间连续（你的思路的严谨版）
// ------------------------------------------------------------
// 首尾是 2 和 14，中间三张连续递增 1：

if (!straight &&
    hand[0][0] == 2 && hand[4][0] == 14 &&
    hand[1][0] == hand[0][0] + 1 &&
    hand[2][0] == hand[1][0] + 1 &&
    hand[3][0] == hand[2][0] + 1)
{
    straight = true;
}

// ------------------------------------------------------------
// * 正确写法 3：循环判断（适合想统一处理的情况）
// ------------------------------------------------------------
// 把 A 当 1 看，判断 hand[0..3] 是否是 2,3,4,5：

bool low_ace = (hand[4][0] == 14 && hand[0][0] == 2);
for (int i = 1; low_ace && i < 4; i++) {
    if (hand[i][0] != hand[i - 1][0] + 1)
        low_ace = false;
}
if (!straight && low_ace)
    straight = true;

// ------------------------------------------------------------
// * 位置总结：
// ------------------------------------------------------------
// 正确顺序：
//   1. 普通 straight 判断（相邻差 1）。
//   2. 如果 straight 为 false，检查小 A 顺。
//   3. straight 为 true 时 return，不再检查四条/三条/对子。
//
// 小 A 顺和普通顺子互斥：
//   普通顺子最小牌不可能是 2 且最大牌是 14（那中间会差 9），
//   所以两个判断不会同时成立，先判断谁都行。
//
// ------------------------------------------------------------
// * 和同花大顺的关系：
// ------------------------------------------------------------
// print_result 里同花大顺条件是：
//     straight && flush && hand[0][0] == 10
// 小 A 顺 hand[0][0] 是 2，不会触发同花大顺，
// 只会走 Straight 或 Straight flush，正确。
//
// 如果小 A 顺也是同花，会输出 "Straight flush"，
// 这是对的：同花小 A 顺就是同花顺的一种。
//
// ------------------------------------------------------------
// * 最小改动（按你的思路，只补严谨性）：
