// 题目：
//   编写函数计算 3x^5 + 2x^4 - 5x^3 - x^2 + 7x - 6。
//   用户输入 x，调用函数计算并显示返回值。
// ============================================================

// * 你的代码（逻辑正确，保留原样，在原处标注）：
#include <stdio.h>

int n(int);   // ⚠️ 函数名 n 太短，看不出含义。
              //    建议改成 polynomial 或 eval_poly，
              //    但当前写法合法，不改也能跑。

int main(void)
{
    int m;

    printf("How much x? ");
    scanf("%d", &m);

    // ✅ 调用函数并直接打印返回值，正确。
    // ⚠️ 输出没有标签、没有换行，建议改成：
    //      printf("Value: %d\n", n(m));
    printf("%d", n(m));

    return 0;
}

int n(int m)
{
    int sum;

    // ✅ 多项式各项完全正确，逐项核对：
    //   3 * m * m * m * m * m  → 3x^5  ✅
    //   2 * m * m * m * m      → 2x^4  ✅
    //  -5 * m * m * m          → -5x^3 ✅
    //   - m * m                → -x^2  ✅
    //   7 * m                  → 7x    ✅
    //   - 6                    → -6    ✅
    sum = 3 * m * m * m * m * m + 2 * m * m * m * m
        - 5 * m * m * m - m * m + 7 * m - 6;

    return sum;
}

