// 第8章 第7题：读取 5×5 整数数组，输出每行和与每列和
// 题目：
//   Enter row 1:  8  3  9  0 10
//   ...
//   Row totals:  30 27 40 36 28
//   Column totals:  34 37 37 32 21
// ============================================================

// * 你的代码（微调：末尾补了 \n，其余保留原样）：
#include <stdio.h>

int main(void)
{
    int num[5][5] = {};   // * 你的注释“空初始化，C23 合法” ✅ 正确。
                          // * C23 起允许空初始化器 {}，所有元素初始化为 0。
                          // ? 若按 C99/C11，应写成 {0}。

    // * 读入 5 行，每行 5 个数。
    // * i 从 1 到 5，对应提示 "Enter row 1" 到 "Enter row 5"；
    // * 存入时用 i-1、n-1，正好映射到 0~4 的下标，正确。
    for (int i = 1; i <= 5; i++) {
        printf("Enter row %d: ", i);
        for (int n = 1; n <= 5; n++) {
            scanf("%d", &num[i - 1][n - 1]);
        }
    }

    // ✅ 行和：外层 i 固定行，内层 n 遍历列，sum1 累加 num[i][n]。
    // * 你的注释“声明到内部，每次循环重新清零计算” ✅ 正确。
    printf("Row totals: ");
    for (int i = 0; i < 5; i++) {
        int sum1 = 0;
        for (int n = 0; n < 5; n++) {
            sum1 += num[i][n];
        }
        printf("%3d", sum1);
    }

    printf("\n");

    // ✅ 列和：外层 i 固定列，内层 n 遍历行，sum2 累加 num[n][i]。
    // * 你的注释“由于这两个 printf 要分开，所以两个 sum 不能在同一个循环里面”
    // ? 这句话不准确。
    // ? 两个 sum 完全可以放在同一个双层循环里同时累加：
    //     for (int i = 0; i < 5; i++) {
    //         int row_sum = 0, col_sum = 0;
    //         for (int n = 0; n < 5; n++) {
    //             row_sum += num[i][n];
    //             col_sum += num[n][i];
    //         }
    //         ...
    //     }
    // ? 只是“分行输出”和“分列输出”需要分开打印，
    // ? 不代表计算必须分成两个循环。
    // ? 你现在的写法完全正确，只是注释里的“不能”过于绝对。
    printf("Column totals: ");
    for (int i = 0; i < 5; i++) {
        int sum2 = 0;
        for (int n = 0; n < 5; n++) {
            sum2 += num[n][i];
        }
        printf("%3d", sum2);
    }

    // * 微调：末尾补 \n，输出更整洁。
    printf("\n");

    return 0;
}

