#include <stdio.h>

void selection_sort(int num[], int n);

int main(void)
{
    int n;

    printf("How many numbers would you need? ");
    scanf("%d", &n);

    // * 先读入 n，再声明 VLA，顺序不能反。
    // * 同时检查 n 是否为正数，避免大小为 0 或负数的 VLA。
    if (n <= 0) {
        printf("n must be a positive integer.\n");
        return 1;
    }

    int num[n];   // * 此时 n 已经有确定值，VLA 大小合法。

    printf("Enter some numbers: ");
    for (int i = 0; i < n; i++)
        scanf("%d", &num[i]);

    selection_sort(num, n);

    for (int i = 0; i < n; i++)
        printf("%d ", num[i]);
    printf("\n");

    return 0;
}

void selection_sort(int num[], int n)
{
    int m;

    // * 0 个或 1 个元素，天然有序，直接返回。
    if (n <= 1)
        return;

    // * 找 0 ~ n-1 中的最大值，放到 num[n-1]。
    // * 用 num[n-1] 作为初始“擂主”，遇到更大的就交换。
    // * 修正：i < n - 1，最后一个元素不需要和自己比较。
    for (int i = 0; i < n - 1; i++) {
        if (num[i] > num[n - 1]) {
            m = num[n - 1];
            num[n - 1] = num[i];
            num[i] = m;
        }
    }

    // * 前 n-1 个元素继续递归排序。
    selection_sort(num, n - 1);
}
// 还可用比下标大小打擂台，谁大就放谁的下标打，最后比出来后再换。

