// 第8章 第13题：修改第7章第11题，给输出加标签
// 题目：
//   Enter a first and last name: Lloyd Fosdick
//   You entered the name: Fosdick, L.
//
//   在显示姓（不是名）之前，程序需要将其存储在一个字符数组中。
//   可以假定姓的长度不超过 20 个字符。
// ============================================================

// * 你的代码（逻辑正确，保留原样，在原处标注）：
#include <stdio.h>

int main(void)
{
    char list[21] = {};   // * 正确：姓不超过 20 个字符，开 21 留一位 '\0'。
                          // * 虽然这里用 for 逐字符输出，不依赖 '\0'，但留一位是好习惯。
    int m;
    int k;
    int n, j = 1;   // * j 初始为 1，因为 list[0] 已经放姓首字母，
                    //   后续从 list[1] 开始，注释理解正确。

    printf("Enter a first and last name: ");

    // * 第一段：跳过前导空格，拿到名首字母存进 m。
    // * 你的注释“只要判断 EOF 就要搞个变量做两次检验”
    //   意思是 while 条件里同时判断字符和 EOF，理解正确。
    // ⚠️ 小提醒：条件顺序建议先判断 EOF，再判断字符：
    //     while ((m = getchar()) != EOF && m == ' ')
    //   现在的顺序 (m == ' ' && m != EOF) 在 m 是 EOF 时，
    //   左边为假直接短路，不会执行 m != EOF，
    //   虽然循环也会退出，但 m 已经是 EOF，
    //   后面如果直接用 m 当首字母会出错。
    //   题目保证输入合法，不会出现 EOF，所以不判错，只是建议调整顺序。
    while ((m = getchar()) == ' ' && m != EOF)
        ;

    // * 第二段：跳过名的剩余部分，直到遇到空格。
    // * 你的注释“筛选不是 ' ' 就一直为真，循环；不是 EOF 就一直为真”
    //   逻辑描述正确。
    // ⚠️ 同上，建议先判断 EOF：while ((k = getchar()) != EOF && k != ' ')
    while ((k = getchar()) != ' ' && k != EOF)
        ;

    // * 第三段：跳过空格，拿到姓的首字母。
    // * 你的注释“判断到空格我把它拿完，第一个姓字符直接放，
    //   由 getchar 转的安全得很”理解正确。
    // * 但如果姓前面有多个空格，这个循环会继续跳过，正确。
    // ⚠️ 同样建议先判断 EOF。
    while ((k = getchar()) == ' ' && k != EOF)
        ;

    // * 姓首字母存入 list[0]。
    list[0] = k;

    // * 第四段：读姓的剩余字符，直到换行。
    // * 你的注释“j++ 放后面是为下次循环做准备，
    //   可最后一次循环没有下次，所以它多了 1（j 是对应下标所以多 1）”
    //   ✅ 正确。j 最终等于姓的长度，for 用 i < j 正好输出 list[0..j-1]。
    while ((n = getchar()) != '\n' && n != EOF) {
        list[j] = n;
        j++;
    }

    // * 输出标签和姓。
    printf("You entered the name: ");
    for (int i = 0; i < j; i++)
        printf("%c", list[i]);

    // * 输出 ", 名首字母."
    // * 你的注释“m 经过 getchar 的转换塞入，用来坐 %c 的地址绝没问题”
    //   ✅ 正确。%c 期望 int 参数，m 是 int，传进去没问题。
    //   这里不是“地址”，是值；printf 中 %c 接收的是值不是地址。
    printf(", %c.\n", m);   // * 微调：末尾加了 \n，输出更整洁。

    return 0;
}

