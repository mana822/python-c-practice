// 13. 修改第 7 章的编程题 11，给输出加上标签：

// Enter a first and last name: Lloyd Fosdick
// You entered the name: Fosdick, L.

// 在显示姓（不是名）之前，程序需要将其存储在一个字符数组中。
// 可以假定姓的长度不超过 20 个字符。


#include <stdio.h>
int main(void)
{
    char list[21] = {};
    int m;
    int k;
    int n, j = 1;  // <-- 后续循环计数用到，因为一次循环且计数，放外面
    printf("Enter a first and last name: ");  // <-- 提交的时候自动换行，不管吃不吃'\n'
    while ((m = getchar()) == ' ' && m != EOF)   // <-- 注意只要判断EOF就要去搞个变量做两次检验
        ;  // <-- break通常情况下代替判断循环会导致后续改变的时候代替空循环';' 

    // 拿到第一个首字母，我们就要用首字母判断为假跳过剔除空格，首字母已经存入m
    while ((k = getchar()) != ' ' && k != EOF) // <-- 一定注意判断符的使用,还有逻辑，我们筛选不是' '就一直为真，循环，不是EOF就一直为真，做表达式判断，心中用真假辨之
        ;
    while ((k = getchar()) == ' ' && k != EOF) // <-- 判断到空格我把它拿完，第一个姓字符直接放，由getchar转的安全的很
        ;
    // 注意，每次判断都要拿字符，所以我们要做判断筛选就选前面一个标志，并且break防止再去读取后续字符。
        list[0] = k;
    while ((n = getchar()) != '\n' && n != EOF) {
        list[j] = n;
        j++;  // <-- j++放后面是为下次循环做准备，可最后一次循环没有下次，所以它多了1(j是对应下标所以多1，所以用'<'就行)
    }
    printf("You entered the name: ");
    for (int i = 0; i < j ; i++) printf("%c", list[i]);
    printf(", %c.", m);  // <-- m经过getchar的转换塞入，用来坐%c的地址绝没问题
    return 0;
    
}


