// ============================================================
// 第8章 第6题：B1FF 过滤器
// 题目：
//   Enter message: Hey dude, C is rilly cool
//   In B1FF-speak: H3Y DUD3, C 15 R1LLY C00L!!!!!!!!!!
//
//   转大写，A→4、B→8、E→3、I→1、O→0、S→5，
//   末尾加 10 个左右感叹号。
//   提示：先把消息存进字符数组，再逐个翻译输出。
// ============================================================

// * 你的代码（逻辑正确，保留原样，在原处标注）：
#include <stdio.h>

int main(void)
{
    int n = -1;
    int num[100] = {};   // ⚠️ 提醒：{} 空初始化器是 C23 才合法的写法。
                         //    C99/C11 下应写成 {0} 或 {0}。
                         //    按 C23 标准，这里没问题。

    int m;
    printf("Enter message: ");   // ✅ 注释正确：不加 \n，用户按回车时终端自然换行。

    // ✅ 逐字符读入数组，n 从 -1 开始，n++ 后 num[0] 存第一个字符。
    //    循环结束时 n 是最后一个字符的下标，后面用 i <= n 遍历，正确。
    while ((m = getchar()) != '\n' && m != EOF) {
        n++;
        num[n] = m;
        // ⚠️ 警告：num 只有 100 个元素，如果输入超过 100 个字符，
        //    n 会超过 99，num[n] 越界写，属于未定义行为。
        //    题目示例很短，不会触发；但严格说应加边界检查，例如：
        //      if (n < 99) { n++; num[n] = m; }
        //    或者把数组开大一些。
    }

    printf("In B1FF-speak: ");   // ✅ 放在读入之后、输出之前，正确。

    for (int i = 0; i <= n; i++) {
        // ✅ 小写转大写逻辑正确。
        // * 你的注释“左值是不允许强转的”✅ 正确：
        //   这里 (char)num[i] 强转的是右值，参与运算后结果仍是 int，
        //   赋给左值 num[i] 没问题。
        // * 你的注释“也可以声明时就用 char”✅ 正确：
        //   直接用 char 数组更自然，也不用强转。
        if ((char)num[i] >= 'a' && (char)num[i] <= 'z')
            num[i] = (char)num[i] - 'a' + 'A';

        // ✅ 字母替换正确。
        // * 你的注释“也可以用 toupper() 搭配 (unsigned int) 强转”
        //   ⚠️ 这里类型写错了：toupper 的参数应转成 unsigned char，
        //   不是 unsigned int。正确写法：
        //     num[i] = toupper((unsigned char)num[i]);
        //   C23 下这个规则没有变化。
        switch (num[i]) {
            case 'A': num[i] = '4'; break;
            case 'B': num[i] = '8'; break;
            case 'E': num[i] = '3'; break;
            case 'I': num[i] = '1'; break;
            case 'O': num[i] = '0'; break;
            case 'S': num[i] = '5'; break;
            default: ; break;   // ✅ 空语句，合法。
        }

        printf("%c", num[i]);   // ✅ 用 %c 输出，正确。
                                // * 你的注释“想试试强转和读取截断这类骚操作”
                                //   ✅ 可以理解。用 int 数组存字符完全能跑，
                                //   只是比 char 数组多占内存，练习目的达到就行。
    }

    // ✅ 10 个感叹号，符合题目“10 个左右”。
    for (int i = 1; i <= 10; i++)
        printf("!");

    // ⚠️ 警告（可选）：末尾建议加 \n，输出更整洁。
    printf("\n");

    return 0;
}

