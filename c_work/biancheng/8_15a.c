// 15. 目前已知的最古老的一种加密技术是恺撒加密（得名于 Julius Caesar）。该方法把一条消息中的每个字母用字母表中固定距离之后的那个字母来替代。
// （如果越过了字母 Z，则会绕回到字母表的起始位置。例如，如果每个字母都用字母表中两个位置之后的字母代替，那么 Y 就被替换为 A，Z 就被替换为 B。）
// 编写程序用恺撒加密方法对消息进行加密。用户输入待加密的消息和移位计数（字母移动的位置数目）：
// Enter message to be encrypted: Go ahead, make my day.
// Enter shift amount (1-25): 3
// Encrypted message: Jr dkhdg, pdnh pb gdb.

#include <stdio.h>

int main(void)
{
    int k;
    int i = 0;
    char list[81] = {};
    
    printf("Enter message to be encrypted: ");
    
    // 【你的思考】：去用getchar拿字符，因为有空格什么的，用getchar是明智的，getchar配int因为转换所以对char是合理的。
    // 【修正补充】：这里声明 ch 为 int 类型非常关键，因为 getchar 返回的是 int，用它来接收能准确判断 EOF。如果只用 char，可能会把某些字符误判为 EOF。
    int ch; 
    
    while ((ch = getchar()) != EOF && ch != '\n' && i < 80) {
        // 【你的思考】：由于只要一个循环就够了我们在里面用计数器。
        // 【你的思考】：我们一定记住i对应什么以及自增在后面的影响。
        list[i] = (char)ch;    
        i++;
    }
    list[i] = '\0'; // 【优化】：养成好习惯，字符数组结尾加上结束符

    // 【你的思考】：所有存储好考虑好怎么转换。
    printf("Enter shift amount (1-25): ");
    scanf("%d", &k);   // 【你的思考】：拿到我们要的偏移量

    printf("Encrypted message: ");

    // 【你的思考】：思考怎么一个个对比。用循环把char一个个取出来加吧，再做一个判断判断范围。
    for (int n = 0; n < i; n++) {
        
        // 【你的思考】：这里分开判断，逻辑更清楚。
        // 【优化】：虽然写两个 if 逻辑上也走得通，但因为一个字符不可能同时是小写又是大写，所以用 else if 更加严谨，效率也更高。
        if (list[n] >= 'a' && list[n] <= 'z') {  
            
            // 【你的思考】：这时考虑一下溢出情况，做一个判断最好。我们这时内层判断，只在字母里面筛选。
            // 【修正致命错误】：如果按照原代码 list[n] += k 然后判断 list[n] > 'z'，会有隐藏的 char 溢出 Bug。
            // 因为 char 默认是有符号的（最大127），如果加上 k 超过 127，它会变成负数，导致 if 判断失效！
            // 【优化】：直接使用题目提示的标准公式，让数学直接搞定“绕回”，不需要额外的 if (list[n] > 'z') 判断。
            list[n] = (list[n] - 'a' + k) % 26 + 'a';    
            
        } 
        else if (list[n] >= 'A' && list[n] <= 'Z') { // 【优化】：改为 else if
            
            // 【优化】：同理，大写字母使用标准公式。
            list[n] = (list[n] - 'A' + k) % 26 + 'A';
        }
        
        // 【你的思考】：既然遍历筛选完了，我们要开始输出了，也是用遍历输出。
        // 【你的思考】：虽然getchar已经转过一次，但是putchar用着不烧心。
        // 【你的思考】：思考，与上面循环高度重合，是否可以合并？结论，不是嵌套循环，不是成堆打印，可以合并(将printf放到循环上面，再把putchar()放进去)
        // 【回答你的疑问】：你说得对！完全可以把加密（转换）和输出合并在一起。因为加密一个字符，就可以立刻把它打印出来，没必要等整个数组都加密完再打印。
        putchar(list[n]); 
    }
    
    printf("\n"); // 原代码这里缺个换行，习惯上最后加上
    return 0;
}

