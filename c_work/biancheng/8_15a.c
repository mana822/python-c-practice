// 题目：
//   Enter message to be encrypted: Go ahead, make my day.
//   Enter shift amount (1-25): 3
//   Encrypted message: Jr dkhdg, pdnh pb gdb.
//
//   每个字母用字母表中固定距离之后的字母替代，越界绕回。
//   非字母字符保持不变。
// ============================================================

// * 你的代码（逻辑完全正确，保留原样，在原处标注）：
#include <stdio.h>

int main(void)
{
    int k;
    int i = 0;
    char list[81] = {};

    printf("Enter message to be encrypted: ");

    // ✅ ch 用 int 接收 getchar，正确。
    // * 你的注释“getchar 返回 int，用它接能准确判断 EOF”
    //   ✅ 完全正确。char 装不下 EOF，用 int 是标准做法。
    int ch;

    // ✅ 循环条件正确：不是 EOF、不是换行、不超过 80 个字符。
    // * i < 80 是必要的边界保护，数组大小 81，留一位给 '\0'。
    while ((ch = getchar()) != EOF && ch != '\n' && i < 80) {
        list[i] = (char)ch;   // * 存入时转回 char，字符本身不会超过 char 范围。
        i++;
    }

    // ✅ 末尾加 '\0'，好习惯。
    // * 本题没有用字符串函数，加不加都不影响输出，
    //   但加上更规范，也方便以后扩展。
    list[i] = '\0';

    printf("Enter shift amount (1-25): ");
    scanf("%d", &k);   // ✅ 读取偏移量，正确。

    printf("Encrypted message: ");

    // ✅ 加密和输出合并在一个循环里，正确。
    // * 你的注释“不是嵌套循环，不是成堆打印，可以合并”
    //   ✅ 正确。每加密一个字符就立刻输出，不需要先全部加密再统一输出。
    for (int n = 0; n < i; n++) {

        // ✅ 小写字母分支。
        // * 你的注释“如果按 list[n] += k 再判断 list[n] > 'z'，会有 char 溢出 Bug”
        //   ✅ 完全正确。'z' = 122，加 3 就是 125，加 25 就是 147，
        //   超过有符号 char 的最大值 127，会变成负数，判断失效。
        // * 标准公式 (c - 'a' + k) % 26 + 'a' 直接在数学上处理绕回，
        //   不依赖额外的 if 判断，也不会溢出。
        //   以 'z' + 3 验证：(122 - 97 + 3) % 26 + 97 = 28 % 26 + 97 = 2 + 97 = 'c'，正确。
        if (list[n] >= 'a' && list[n] <= 'z') {
            list[n] = (list[n] - 'a' + k) % 26 + 'a';
        }
        // ✅ else if 比两个独立 if 更严谨。
        // * 你的注释“一个字符不可能同时是小写又是大写，else if 更严谨”
        //   ✅ 正确。两个独立 if 也能跑对，但 else if 语义更清晰，
        //   也少一次无意义的判断。
        else if (list[n] >= 'A' && list[n] <= 'Z') {
            list[n] = (list[n] - 'A' + k) % 26 + 'A';
        }

        // ✅ 非字母字符不进入任何分支，原样输出，符合题目要求。
        // * 你的注释“putchar 用着不烧心” ✅ 正确。
        //   putchar 接收 int，输出字符，和 getchar 配对使用很自然。
        putchar(list[n]);
    }

    // ✅ 末尾换行，好习惯。
    printf("\n");

    return 0;
}

