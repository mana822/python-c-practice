// ============================================================
// 第8章 第5题：interest.c 改为每月计息一次，输出仍按年显示
// 题目：
//   修改 8.1 节的 interest.c，使得修改后的程序可以每月整合一次利息，
//   而不是每年整合一次利息。不要改变程序的输出格式，
//   余额仍按每年一次的时间间隔显示。
// ============================================================

// * 你的代码（逻辑正确，保留原样）：
#include <stdio.h>

#define NUM_RATES ((int) (sizeof(value) / sizeof(value[0])))
#define INITIAL_BALANCE 100.00

int main(void)
{
    int i, low_rate, num_years, year;
    double value[5];

    printf("Enter interest rate: ");
    scanf("%d", &low_rate);

    printf("Enter number of years: ");
    scanf("%d", &num_years);

    printf("\nYears");
    for (i = 0; i < NUM_RATES; i++) {
        printf("%6d%%", low_rate + i);
        value[i] = INITIAL_BALANCE;
    }
    printf("\n");

    for (year = 1; year <= num_years; year++) {
        printf("%3d    ", year);

        for (i = 0; i < NUM_RATES; i++) {
            // * 正确：内层再循环 12 次，每月计息一次。
            // * 月利率 = 年利率 / 12 / 100，
            // * 每月 value[i] += 月利率 * value[i]，
            // * 12 个月就是一年，输出时机仍然是每年一次。
            for (int n = 1; n <= 12; n++) {
                value[i] += (low_rate + i) / 12.0 / 100.0 * value[i];
            }

            // * 每年末输出一次余额，格式与原来一致。
            printf("%7.2f", value[i]);
        }

        printf("\n");
    }

    return 0;
}

// ============================================================
// 批改总结：
// ✅ 完全正确。
//   - 内层 for (n = 1; n <= 12; n++) 每月计息一次，符合题目要求。
//   - 月利率 (low_rate + i) / 12.0 / 100.0 计算正确：
//     先除 12 得到月利率百分数，再除 100 转成小数。
//   - 12 次复利后再输出，输出时机仍是每年一次，格式没变。
//   - 表头、列宽 %7.2f、换行位置都与原程序一致。
//
// ⚠️ 提醒（不是错误）：月复利结果会略高于年复利。
//   年复利：value *= (1 + r)
//   月复利：value *= (1 + r/12)^12
//   因为 (1 + r/12)^12 > 1 + r（r > 0 时），
//   所以同样的年利率下，按月计息的余额会比按年计息略高。
//   这是正确的金融计算结果，不是程序错误。
//
// ? 补充：
//   1. (low_rate + i) / 12.0 / 100.0 中，
//      12.0 和 100.0 是 double，保证除法是浮点除法，
//      不会像整数除法那样截断。
//   2. 内层 for 里声明 int n 是 C99 写法，C23 同样支持，
//      如果编译器只支持 C89，需要把 n 提到外面声明。
//   3. NUM_RATES 依赖 value 数组，宏展开时 value 已声明，合法。
// ============================================================