// * 批改：
//
// ❌ 核心错误：偶数分支没有按题目要求写。
//   题目要求：x^n = (x^(n/2))^2
//   你写的是：x * x * power(x, n - 2)
//
//   数学上两者都等于 x^n，结果正确，
//   但你的写法没有实现题目的“更快”。
//
//   对比递归深度（以 n = 1024 为例）：
//     你的写法：n 每次减 2，深度 512；
//     正确写法：n 每次折半，深度 10（log2(1024) = 10）。
//   所以你的写法本质上还是线性递归，没有达到快速幂的 log(n) 复杂度。
//
//   正确写法：
//     int half = power(x, n / 2);
//     return half * half;
//   先递归算 x^(n/2)，再把结果自乘一次。
//
// ❌ 注释错误：
//   “这是给递归的最终条件终止，对前面的都无效”
//   不对。n == 0 是递归基例，每一层递归最终都会走到这里，
//   然后逐层返回 1，再逐层乘回去。
//   它不是“只对最后一层有效”，而是整个递归展开的终点。
//
// ✅ 奇数分支正确：
//   x * power(x, n - 1)，n - 1 变成偶数，下一层走偶数分支。
//   你的注释“相当于拆解成偶数了”理解正确。
//
// ⚠️ 小问题（不是核心错误）：
//   1. 输出没有标签和换行，建议加：
//        printf("%d^%d = %d\n", x, n, sum);
//   2. 变量名 sum 不直观，实际存的是幂值，建议改成 result。
//
// ------------------------------------------------------------
// * 正确版本（本文件唯一可运行的 main）：
// ------------------------------------------------------------

#include <stdio.h>

int power(int x, int n);

int main(void)
{
    int x, n;

    printf("Enter x and n: ");
    scanf("%d %d", &x, &n);

    int result = power(x, n);

    // * 加标签和换行，输出更清晰。
    printf("%d^%d = %d\n", x, n, result);

    return 0;
}

int power(int x, int n)
{
    // * 递归基例：任何数的 0 次方都是 1。
    // * 每一层递归最终都会走到这里，再逐层返回结果。
    if (n == 0)
        return 1;

    if (n % 2 == 0) {
        // * 偶数：x^n = (x^(n/2))^2。
        // * 先递归算 x^(n/2)，再把结果自乘一次。
        // * 递归深度是 log2(n)，比每次减 2 快得多。
        int half = power(x, n / 2);  // <-- 先拿值，拿到返回乘后面的数
        return half * half;     // <-- 还是返回到上一个函数的 int half 调用那边，不用担心
    } else {
        // * 奇数：x^n = x * x^(n-1)，n-1 变成偶数。
        return x * power(x, n - 1);   // <-- 这里的变成奇数和最后递归的那个x*1刚好对应
    }
}

// * 验证：
//   x = 2, n = 10：
//     power(2, 10) = power(2, 5)^2
//     power(2, 5)  = 2 * power(2, 4)
//     power(2, 4)  = power(2, 2)^2
//     power(2, 2)  = power(2, 1)^2
//     power(2, 1)  = 2 * power(2, 0) = 2
//     power(2, 2)  = 2^2 = 4
//     power(2, 4)  = 4^2 = 16
//     power(2, 5)  = 2 * 16 = 32
//     power(2, 10) = 32^2 = 1024  ✅
//
//   x = 3, n = 5：
//     power(3, 5) = 3 * power(3, 4)
//     power(3, 4) = power(3, 2)^2 = 9^2 = 81
//     power(3, 5) = 3 * 81 = 243  ✅

