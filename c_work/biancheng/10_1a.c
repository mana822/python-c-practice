// ============================================================
// * 设计说明（为什么这样写）：
// ============================================================
// 1. 栈存 char 而不是 int：
//    题目要求存储字符，push/pop 参数和返回值都改成 char。
//
// 2. 左括号入栈，右括号弹栈并配对：
//    这是括号匹配的标准做法，利用栈的后进先出特性，
//    保证最近打开的括号最先被关闭。
//
// 3. 右括号多余的情况：
//    栈空时遇到右括号，调用 pop 会触发 stack_underflow，
//    直接输出不匹配并终止，符合题目“曾经调用过 stack_underflow 则视为不匹配”。
//
// 4. 左括号多余的情况：
//    换行后栈非空，说明还有左括号没被关闭，
//    输出不匹配，不终止，只是正常返回 0。
//
// 5. 非括号字符：
//    直接忽略，不压栈不弹栈，符合题目“只检查括号”的要求。
//
// 6. stack_overflow：
//    题目要求显示 "Stack overflow" 并立即终止，
//    用 exit(EXIT_FAILURE) 实现，与教材 10.2 节风格一致。
// ============================================================



