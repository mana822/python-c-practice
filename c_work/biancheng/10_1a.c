// ============================================================
// 第10章 第1题：用栈检查圆括号/花括号嵌套是否正确
// 题目：
//   修改 10.2 节的栈示例，使其存储字符而不是整数。
//   增加 main 函数，读入一串圆括号或花括号，判断嵌套是否正确。
//
//   规则：
//     左括号入栈；
//     右括号弹出栈顶并检查是否匹配；
//     换行时检查栈是否为空，空则匹配，否则不匹配；
//     stack_overflow 显示 "Stack overflow" 并立即终止；
//     调用过 stack_underflow（右括号多余）则视为不匹配。
// ============================================================

#include <stdio.h>
#include <stdlib.h>
#include <stdbool.h>

#define STACK_SIZE 100

// ============================================================
// * 栈部分：与 10.2 节结构相同，只把 int 改成 char
// ============================================================

// * 栈的存储：现在存字符，不是整数。
char contents[STACK_SIZE];
int top = 0;

void make_empty(void)
{
    top = 0;
}

bool is_empty(void)
{
    return top == 0;
}

bool is_full(void)
{
    return top == STACK_SIZE;
}

// * 栈溢出：题目要求显示 "Stack overflow" 并立即终止。
void stack_overflow(void)
{
    printf("Stack overflow\n");
    exit(EXIT_FAILURE);
}

// * 栈下溢：出现在右括号多余时。
// * 题目说“如果曾经调用过 stack_underflow 函数，那么不匹配”，
// * 这里直接输出不匹配信息并终止，效果一致。
void stack_underflow(void)
{
    printf("Parentheses/braces are not nested properly\n");
    exit(EXIT_FAILURE);
}

// * 压栈：参数类型从 int 改成 char。
void push(char c)
{
    if (is_full())    // <-- 满了就不能压了
        stack_overflow();
    else
        contents[top++] = c;
}

// * 弹栈：返回值类型从 int 改成 char。
char pop(void)
{
    if (is_empty())    // <-- 到最后就不能弹了，这里是读取到')'或'}'才去弹，拿的值就是弹出的值，0就不可能是
        stack_underflow();
    else
        return contents[--top];   // <-- 返回的就是上一个压入的

    return '\0';   // * stack_underflow 会 exit，这行不会执行；
                   // * 加在这里只是为了消除“可能没有返回值”的警告。(有if-else在，不会警告)
}

// ============================================================
// * main：读入括号串，判断嵌套
// ============================================================

int main(void)
{
    char ch;

    printf("Enter parentheses and/or braces: ");

    // * 逐字符读入，遇到换行结束。
    while ((ch = getchar()) != '\n' && ch != EOF) {

        // * 左括号：压栈，等待匹配。
        if (ch == '(' || ch == '{') {
            push(ch);
        }
        // * 右括号：弹出栈顶，检查是否与当前右括号配对。
        else if (ch == ')' || ch == '}') {
            char open = pop();    // 弹出的就是当时压入的，这里不是让你知道指针怎么指，而是压入弹出什么

            // * 不匹配的两种情况：
            // *   当前是 ')'，栈顶不是 '('
            // *   当前是 '}'，栈顶不是 '{'
            // * 只要有一个不成立，就直接判定不匹配。
            if ((ch == ')' && open != '(') ||   // 返回的就是当时压入的
                (ch == '}' && open != '{')) {
                printf("Parentheses/braces are not nested properly\n");
                return 0;
            }
        }
        // * 其他字符（数字、字母、空格等）直接忽略，符合题目“只检查括号”。
    }

    // * 换行后检查栈：
    // *   栈空 → 所有左括号都被匹配，嵌套正确；
    // *   栈非空 → 还有未闭合的左括号，嵌套不正确。
    if (is_empty())
        printf("Parentheses/braces are nested properly\n");
    else
        printf("Parentheses/braces are not nested properly\n");

    return 0;
}

