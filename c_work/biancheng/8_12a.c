#include <stdio.h>
#include <ctype.h>

int main(void)
{
    int list[26] = {1, 3, 3, 2, 1, 4, 2, 4, 1, 8,
                    5, 1, 3, 1, 1, 3, 10, 1, 1, 1, 1, 4, 4, 8, 4, 10};
    int sum = 0;
    int n = 0;

    printf("Enter a word: ");

    // * 第一步：在循环外先读第一个字符。
    // * 你的注释“n 已经初始化，不怕高位有垃圾值”：
    //   ✅ 实际运行层面正确。
    //   scanf("%c", &n) 只写 1 个字节，剩余字节保留原值；
    //   n 初始化为 0，剩余字节是 0，所以读出来的 int 值就是字符的 ASCII 码。
    //   如果不初始化，剩余字节是不确定值，读出来就是 UB。
    //   ⚠️ 但标准层面，%c 要求 char*，传 int* 仍是类型错配。
    //   初始化只是让“实际运行”稳定，没有消除类型错配本身。
    scanf("%c", &n);

    // * 第二步：拿着第一个字符进循环判断。
    // * 你的注释“必须加 n != EOF，否则空文件会死循环”：
    //   ✅ 正确。EOF 是 -1，不加判断会一直循环。
    while (n != '\n' && n != EOF) { // !=EOF永远不成立，scanf读到EOF不会写入，直接返回

        // * 转大写。toupper 参数转 unsigned char，正确。
        int upper_n = toupper((unsigned char)n);

        // * 只处理 A~Z，非字母跳过，不会越界。
        if (upper_n >= 'A' && upper_n <= 'Z') {
            sum += list[upper_n - 'A'];
        }

        // * 第三步：处理完当前字符后，读下一个。
        scanf("%c", &n);
    }

    printf("Scrabble value: %d\n", sum);
    return 0;
}

