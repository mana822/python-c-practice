// 14. 编写程序颠倒句子中单词的顺序：

// Enter a sentence: you can cage a swallow can't you?
// Reversal of sentence: you can't swallow a cage can you?

// 提示：用循环逐个读取字符，然后将它们存储在一个一维字符数组中。当遇到句号、问号或者感叹号（称为“终止字符”）时，终止循环并把终止字符存储在一个 char 类型变量中。
// 然后再用一个循环反向搜索数组，找到最后一个单词的起始位置。显示最后一个单词，然后反向搜索倒数第二个单词。重复这一过程，直至到达数组的起始位置。最后显示出终止字符。


#include <stdio.h>

int main(void)
{
    int m, n;
    int j = 0;
    int i = 0;   //  <-- 做循环计数，写外边 
    char list[100][20] = {}; // 由于没有字符串数组，我只能用二维去试试
    printf("Enter a sentence: ");
    
    while ((m = getchar()) != EOF && m == ' ')
        ;
    // 先把前面的空格拿了，考虑第一个值怎么处理
    list[0][0] = m; // <-- 直接装进去
    while ((n = getchar()) != EOF && n != '.' && n != '?' && n != '!') {
        // 思考，每个单词用空格隔开，判断空格是关键，在这之间计数

        // 判断条件的同时，最后的n也就是我们要的符号

        if (i == 0) {   // <-- 第0行是特殊的，它判断了空格，提前填了值
            if (n != ' ') { list[i][j+1] = n; j++;}  // <--每次没事别到空格时，没事别到一个加入进去就换一列 
            else if (n == ' ' || n == '?' || n == '!' || n == '.') {  // <-- 识别到空格，分到另一个区域(下标)
            list[i][j+2] = '\0'; i++, j = 0; }    // <-- 对应下标，且在末尾，对应下次循环值
               continue;      // <-- 执行完特殊的跳过就行了,不然后面乱套，没有判断
        } 
        if (n != ' ') { list[i][j] = n; j++;}  // <--每次没事别到空格时，没事别到一个加入进去就换一列 
        else if (n == ' ' || n == '?' || n == '!' || n == '.') {list[i][j+1] = '\0'; i++, j = 0;}  // <-- 识别到空格，分到另一个区域(下标)   注意，行是逐渐往下的，但是列却要重置，本质上是嵌套循环
    }                             // 这里考虑到后面打印，每次循环它的列是不确定的，我们用'\0'封底
    
    printf("Reversal of sentence: ");
    for (int n = i; n >= 0; n--)  {// <-- 这是外层行的循环，我们该考虑的是内层怎么办
        for (int col = 0; list[n][col] != '\0'; col++)  // <-- 单词是正的，我们逐个打印就行，注意封底做判断
        printf("%c", list[n][col]);

    if (n > 0) {   // <-- 判断n
        printf(" ");   // <-- 每一次循环打印，最后一次不用
    }
}
    printf("%c\n", n);
    return 0;    

}


