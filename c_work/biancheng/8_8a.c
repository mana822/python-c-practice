// 第二是，像那种比大小加上嵌套循环，我们要同样避免第一个“擂台主”在内层循环，每次暴力检索都会重置，也是放外面，且注意每次大循环的值(每次小循环都不变)给正确的下标
// 第三是，二维数组要把循环完的整体放一起，且有多个要循环的值时，它们是不能放一起循环的的，不然打印的时候是一条条的零散的。