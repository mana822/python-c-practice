// ============================================================
// 第8章 第8题：5 个学生 5 门测验的成绩统计
// 题目：
//   输入每个学生 5 门测验的成绩，共 5 个学生。
//   计算每个学生的总分和平均分，
//   以及每门测验的平均分、高分和低分。
// ============================================================

// * 你的代码（逻辑正确，保留原样，在原处标注）：
#include <stdio.h>

int main(void)
{
    int num[5][5] = {};   // * C23 下空初始化器合法，全部元素初始化为 0。

    // ✅ 读入部分正确：
    //    i 从 1 到 5 对应学生 1~5，n 从 1 到 5 对应科目 1~5，
    //    存入 num[i-1][n-1]，下标映射正确。
    for (int i = 1; i <= 5; i++) {
        printf("第%d个学生输入你的成绩\n", i);
        for (int n = 1; n <= 5; n++) {
            printf("第%d门科目: ", n);
            scanf("%d", &num[i - 1][n - 1]);
        }
    }

    // ✅ 学生总分和平均分：外层 i 固定学生，内层 n 遍历科目，正确。
    // * 你的注释“初始化在每次大循环排查，因为这些都是为了里面的小循环准备的”✅ 正确。
    for (int i = 0; i < 5; i++) {
        float sum = 0, mean = 0;

        // ⚠️ 警告：下面这些变量在第一个循环里完全没用到。
        //    max/min 是给第二个循环（科目统计）准备的，
        //    mean1/sum1 也是给第二个循环准备的。
        //    在第一个循环里声明它们属于多余，建议删掉，只留 sum 和 mean。
        //    float max = 0, min = 0, mean1 = 0, sum1 = 0;

        for (int n = 0; n < 5; n++) {
            sum += num[i][n];
        }
        mean = sum / 5;

        // ⚠️ 警告：这行也是多余的，sum1 在第一个循环里始终是 0，
        //    mean1 算出来也是 0，而且后面没用到。
        //    mean1 = sum1 / 5;

        printf("第%d个同学的总成绩是%.2f,平均分是%.2f\n",
               i + 1, sum, mean);
    }

    // ✅ 科目平均分、最高分、最低分：外层 i 固定科目，内层 n 遍历学生，正确。
    // * 你的注释“每次循环检索的是那一门科目的不同人成绩，所以那门科目(也就是i)不会变”
    //   ✅ 正确：i 是科目列下标，内层 n 是学生行下标，num[n][i] 正好取第 i 门科目所有学生的成绩。
    for (int i = 0; i < 5; i++) {
        // * 你的注释“初始化在每次大循环排查，因为这些都是为了里面的小循环准备的”
        //   ✅ 正确。每次换一门科目，sum1/max/min 都要重新初始化。
        float max = 0, min = 0, mean1 = 0, sum1 = 0;

        // * 你的注释“这里随便找一个确定的值，且每个科目要跟着变”
        //   ✅ 正确。max/min 先取第 0 个学生的成绩作为“擂台主”，
        //   然后内层遍历所有学生，逐个比较。
        max = num[0][i];
        min = num[0][i];

        for (int n = 0; n < 5; n++) {
            sum1 += num[n][i];

            if (num[n][i] > max) max = num[n][i];
            if (num[n][i] < min) min = num[n][i];
        }

        mean1 = sum1 / 5;

        printf("第%d门科目的平均分是%.2f,最高分是%.2f,最低分是%.2f\n",
               i + 1, mean1, max, min);
    }

    return 0;
}

