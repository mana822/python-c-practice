//   max/min 存的是整数成绩，用 float 再输出 %.2f 会显示 8.00 这种，
//   题目说“高分和低分”，用 int + %d 更自然，但不改也正确。
//
// ============================================================
// * 你的三点总结，逐条回应：
// ============================================================
// 1. “嵌套循环，外层看重次数，内层看重逐个检索，初始化要放外层循环内、内层循环前。”
//    ✅ 正确。每次外层换一轮，内层要重新开始累加/比较，
//    所以 sum、max、min 必须在进入内层之前重置。
//
// 2. “比大小加嵌套循环，第一个‘擂台主’不能放内层循环，否则每次暴力检索都会重置；
//    放外面，且注意每次大循环的值给正确的下标。”
//    ✅ 正确。本题 max = num[0][i] 放在内层循环外，
//    i 是当前科目列，内层 n 遍历行，下标对应正确。
//    如果写成 num[0][0]，就变成所有科目都用第 0 列当擂台主，错误。
//
// 3. “二维数组要把循环完的整体放一起，且有多个要循环的值时，它们不能放一起循环，
//    不然打印的时候是一条条的零散的。”
//    ⚠️ 这句话不准确。
//    计算完全可以放在同一个双层循环里同时做：
//      for (i = 0; i < 5; i++) {
//          int row_sum = 0, col_sum = 0;
//          for (n = 0; n < 5; n++) {
//              row_sum += num[i][n];
//              col_sum += num[n][i];
//          }
//          ...
//      }
//    这样行和、列和都能一次算完。
//    你分成两个循环，真正的原因是“输出要分组”：
//    先输出所有学生的总分/平均分，再输出所有科目的统计，
//    分两个循环打印更清晰。
//    所以准确说法是：
//      “为了输出分组清晰，分成两个循环分别打印；
//       计算本身可以合并，不是语言限制。”
//
// * C23 变化：
//   int num[5][5] = {}; 空初始化器在 C23 合法；
//   C99/C11 下应写成 {0}。
//   其余部分没有 C23 特有变化。
// ============================================================

