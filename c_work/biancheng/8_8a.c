//   - 学生总分/平均分：外层学生、内层科目，正确。
//   - 科目平均分/最高分/最低分：外层科目、内层学生，正确。
//   - max/min 的“擂台主”初始化用 num[0][i]，正确。
//
// ⚠️ 警告（不是错误）：
//   第一个循环里声明了 max、min、mean1、sum1，但完全没用到。
//   这些变量是给第二个循环准备的，应删掉，只保留 sum 和 mean。
//   mean1 = sum1 / 5; 这一行也是多余的，sum1 在第一个循环里始终为 0。
//
