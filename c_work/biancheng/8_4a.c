// ============================================================
// 第8章 第4题：修改 reverse.c，用 sizeof 计算数组长度
// 题目：
//   修改 8.1 节的程序 reverse.c，利用表达式
//   (int)(sizeof(a) / sizeof(a[0]))（或者具有相同值的宏）
//   来计算数组的长度。
// ============================================================

// * 你的代码（微调：第二个循环也改用 A，保持一致性）：
#include <stdio.h>

#define N 10
#define A ((int) (sizeof(a) / sizeof(a[0])))

int main(void)
{
    int a[N], i;

    printf("Enter %d numbers: ", N);

    // ✅ 第一个循环用 A 控制，符合题目要求。
    for (i = 0; i < A; i++)
        scanf("%d", &a[i]);

    printf("In reverse order: ");

    // ! 原代码这里写的是 N - 1，没有用 A。
    // ! 虽然本题 N 和 A 都等于 10，结果一样，
    // ! 但题目要求“利用表达式计算数组长度”，
    // ! 两个循环都应统一用 A，否则只改了一半。
    // * 微调：改成 A - 1。
    for (i = A - 1; i >= 0; i--)
        printf(" %d", a[i]);

    printf("\n");
    return 0;
}

// ============================================================
// 批改总结：
// ✅ 宏 A 的写法正确：
//    #define A ((int)(sizeof(a) / sizeof(a[0])))
//    在 main 内展开时 a 已声明，sizeof 合法。
//    外层多加一层括号是好习惯，避免宏展开时优先级问题。
//
// ✅ 第一个循环用 A 控制，正确。
//
// ❌ 第二个循环写的是 N - 1，没有用 A。
//    虽然本题 N == A == 10，结果相同，
//    但题目要求利用表达式计算长度，两处应统一用 A。
//    应改为：for (i = A - 1; i >= 0; i--)
//
// ✅ 你的注释“从 N-1 开始，到 0 结束，刚好是倒着来”理解正确，
//    改成 A - 1 后逻辑不变。
//
// ? 补充：
//    宏 A 依赖数组 a，所以必须在 a 声明之后展开使用。
//    你的代码在 main 内使用 A，a 已声明，合法。
//    如果有人把 A 用在 a 声明之前，会编译失败，
//    这是这种写法的固有限制，不是本题的错误。
//
// ? C23 变化：sizeof 仍是运算符，返回 size_t，
//    强转 int 对长度 10 完全安全；
//    C23 下没有与本题相关的规则变化。
// ============================================================