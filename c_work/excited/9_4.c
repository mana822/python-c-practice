// 15. 下面这个（相当混乱的）函数找出三个数的中间数。重新编写函数，使得它只有一条 return 语句。
// double median(double x, double y, double z)
// {
//     if (x <= y)
//         if (y <= z) return y;
//         else if (x <= z) return z;
//         else return x;
//     if (z <= y) return y;
//     if (x <= z) return x;
//     return z;
// }
// ============================================================
// * 你的原版（整体注释，块内用【】）：
/*
double median(double x, double y, double z)
{
    double max;
    max = x;
    if (y > max) max = y;
    if (z > max) max = z;
    return max;
}
*/
// ❌ 错。你算的是最大值，不是中间数。
// ? 一条 return 求中间数：和 - 最大值 - 最小值 = 中间数。
// * 验证：median(3,1,2) → 6-3-1=2 ✅（你的 max 版返回 3 ❌）
// 批改总结：❌算成最大值 ✅只有一条 return 的形式对
double median(double x, double y, double z)
{
    double min, max;
    min = x < y ? (x < z ? x : z) : (y < z ? y : z);
    max = x > y ? (x > z ? x : z) : (y > z ? y : z);
    return x + y + z - min - max;
}

