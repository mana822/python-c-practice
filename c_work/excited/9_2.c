// 第9章 9.2节 第8题：不返回值且有一个 double 形参，哪些原型有效？
// (a) void f(double x);
// (b) void f(double);
// (c) void f(x);
// (d) f(double x);
// ============================================================

// * 你的答案（保留原样）：
//   答(a):有效;(b)有效;(c)有效;(d)无效。

// * 批改（逐项）：
// ✅ (a) 有效。void 返回类型 + double 形参，带形参名，标准原型，正确。
// ✅ (b) 有效。原型中形参名可以省略，只写类型 double，正确。
// ❌ (c) 你答"有效"——错。void f(x); 形参 x 没有类型。
//        旧 C89 会把 x 当隐式 int，那也不是 double，不符合题目"double 形参"；
//        C99 起隐式 int 被移除，这是编译错误。所以 (c) 无效。
// ✅ (d) 你答"无效"——对。f(double x); 缺少返回类型。
//        旧规则默认返回 int，也不是"不返回值(void)"；C99+ 隐式 int 返回被移除，
//        是编译错误。无效判断正确。

// * 验证：
//   (a)(b) 能通过编译 ✅
//   (c)(d) 在 C23 下都是编译错误 ❌

