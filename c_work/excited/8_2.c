// * 批改：
// ❌ 错误：你算的是“每天的平均温度”，不是“整个月的平均温度”。
//   题目要求“计算一个月的平均温度（对每月中的每天和每天中的每小时取平均）”，
//   也就是把 30×24 个读数全部加起来，除以 30×24。
//   你的代码在每天内层循环结束后就 sum /= n 并输出，
//   得到的是每天的平均，没有求整月的总平均。
//
// * 正确做法：
//   1. 双层循环遍历 30×24 个元素，全部累加到 sum。
//   2. 最后 sum / (30 * 24) 得到整月平均温度。
//   3. 不需要每天单独输出平均。
//
// * 修正版（本文件唯一可运行的 main）：
#include <stdio.h>

int main(void)
{
    double temperature_readings[30][24] = {0};
    double sum = 0.0;
    int i, j;

    // * 读入 30 天 × 24 小时的温度。
    for (i = 0; i < 30; i++) {
        for (j = 0; j < 24; j++) {
            printf("Enter day %d hour %d temperature: ", i + 1, j);
            scanf("%lf", &temperature_readings[i][j]);
        }
    }

    // * 把所有读数累加。
    for (i = 0; i < 30; i++) {
        for (j = 0; j < 24; j++) {
            sum += temperature_readings[i][j];
        }
    }

    // * 整月平均温度。
    printf("Average temperature for the month: %.2f\n",
           sum / (30.0 * 24.0));

    return 0;
}

// * 关键点：
//   - sum 初始化为 0.0。
//   - 累加所有 720 个读数。
//   - 除以 30*24，不是除以 24。
//   - 不需要每天单独输出平均。
//
// * 补充：如果题目还要求每天的平局温度，可以在每天内层循环后
//   单独计算并输出，但整月平均必须另外累加全部读数。

