// ------------------------------------------------------------
// * 第1题
// 程序框架：
//   int a;
//   void f(int b) { int c; }
//   void g(void) { int d; { int e; } }
//   int main(void) { int f; }
//
// 你的原答：
// 1.答: (a) a,c,b  (b) a,d,e  (c) a,d,e  (d) a,f
// ------------------------------------------------------------

// (a) f 函数
// ✅ 正确。
// f 的函数体作用域内可见：
//   全局 a、形参 b、局部 c。
// 答案：a, b, c（顺序无所谓）

// (b) g 函数
// ❌ 错误：多列了 e。
// “g 函数”指 g 的函数体顶层块作用域，不包括内层块 { int e; }。
// e 只在内层块内可见，不在 g 函数体顶层块作用域。
// g 函数体作用域内可见：
//   全局 a、g 的局部 d。
// 正确答案：a, d

// (c) 声明 e 的程序块
// ✅ 正确。
// 内层块嵌套在 g 函数体内，外层可见的变量仍然可见：
//   全局 a、g 的局部 d、内层块局部 e。
// 答案：a, d, e

// (d) main 函数
// ✅ 正确。
// main 函数体作用域内可见：
//   全局 a、main 的局部 f。
// 注意：局部 f 与函数 f 同名，但题目只列变量名和形参名，
// 不列函数名，所以这里只写变量 f。
// 答案：a, f

// * 第1题正确答案：
// (a) a, b, c
// (b) a, d
// (c) a, d, e
// (d) a, f

// ============================================================
// * 第2题
// 程序框架：
//   int b, c;
//   void f(void) { int b, d; }
//   void g(int a) { int c; { int a, d; } }
//   int main(void) { int c, d; }
//
// 你的原答：
// 2.答:
// (a) b(全局), c, b, d
// (b) a(形参), b, c, c(局部), a(局部), d
// (c) a, b, c, c(g局部), b(局部), d(main), d(g), c(main局部)
// (d) b, c, c(局部), d
// ------------------------------------------------------------

// (a) f 函数
// ✅ 基本正确，但建议标明哪个是全局、哪个是局部。
// f 函数体作用域内：
//   全局 b、全局 c、f 的局部 b（遮蔽全局 b）、f 的局部 d。
// 正确答案：
//   b(全局), c(全局), b(f 局部), d(f 局部)

// (b) g 函数
// ❌ 错误：多列了内层块的 a 和 d。
// “g 函数”指 g 的函数体顶层块作用域，不包括内层块 { int a, d; }。
// g 函数体顶层块作用域内：
//   全局 b、全局 c（被 g 的局部 c 遮蔽）、
//   形参 a、g 的局部 c（遮蔽全局 c）。
// 内层块的 a、d 不在这个作用域内。
// 正确答案：
//   b(全局), c(全局), a(形参), c(g 局部)

// (c) 声明 a 和 d 的程序块
// ❌ 错误：列了 main 的 d、c，这些不在该块作用域内。
// 该块是 g 函数体内的内层块，嵌套在 g 函数体块内。
// 该块作用域内可见：
//   全局 b
//   全局 c（被 g 的局部 c 遮蔽）
//   g 的形参 a（被内层块局部 a 遮蔽）
//   g 的局部 c
//   内层块局部 a（遮蔽形参 a）
//   内层块局部 d
// 正确答案：
//   b(全局), c(全局), a(g 形参), c(g 局部),
//   a(内层块局部), d(内层块局部)

// (d) main 函数
// ✅ 基本正确，但建议标明全局/局部。
// main 函数体作用域内：
//   全局 b、全局 c（被 main 的局部 c 遮蔽）、
//   main 的局部 c、main 的局部 d。
// 正确答案：
//   b(全局), c(全局), c(main 局部), d(main 局部)

// * 第2题正确答案汇总：
// (a) b(全局), c(全局), b(f 局部), d(f 局部)
// (b) b(全局), c(全局), a(g 形参), c(g 局部)
// (c) b(全局), c(全局), a(g 形参), c(g 局部),
//     a(内层块局部), d(内层块局部)
// (d) b(全局), c(全局), c(main 局部), d(main 局部)

// ============================================================
// * 第3题
// 如果程序只有一个函数 main，那么它最多可以包含多少个名为 i 的不同变量？
//
// 你的原答：
// 3.答: 无数个
// ------------------------------------------------------------
// ✅ 正确。
// C 允许块嵌套，每进入一个内层块就可以声明一个新的 i，
// 内层 i 会遮蔽外层 i。嵌套深度理论没有上限，
// 所以名为 i 的不同变量数量理论上是无限多个。
// 实际受编译器资源、栈大小等限制，但标准上不限制数量。
// 更严谨的表述：
//   理论上无限多个，实际受实现限制。

// ============================================================
// 批改总结：
// ============================================================
// 第1题：
// (a) ✅  (b) ❌ 多列 e，应为 a,d  (c) ✅  (d) ✅
//
// 第2题：
// (a) ✅ 基本正确，建议标明全局/局部
// (b) ❌ 多列内层块 a,d，应为 b(全局),c(全局),a(形参),c(g局部)
// (c) ❌ 列了 main 的变量，应为
//     b(全局),c(全局),a(g形参),c(g局部),a(内层块局部),d(内层块局部)
// (d) ✅ 基本正确，建议标明全局/局部
//
// 第3题：✅ 正确，理论上无限多个，实际受实现限制。
//
// 关键点：
// “f 函数”“g 函数”作用域指函数体顶层块作用域，
// 不包括内层块中声明的变量；
// 内层块中声明的变量只在该块及其更深层块内可见。
// 同名变量要区分全局、函数局部、形参、内层块局部。
