// ============================================================
// 第9章 第1题：找出三角形面积函数的两处错误
// 提示：公式没有错误。
// ============================================================
// * 你的答案：(1) hight 形参不能共享 double，height 前加 double。
//             (2) double product; 完全多余，直接删掉。
// ✅ (1) 正确。每个形参都要单独写类型，height 补 double 对。
// ❌ (2) 错误。product 不过余，公式也没错。真正的第二处错误是原题里
//        double product; 写在函数体外面（形参表和 { 之间），属非法位置。
// ⚠️ 你贴的题 product 已在 { 内，所以看不出——核对教材原题。
// ? K&R 旧式写法：double product; 在 { 外，C99 后非法。
// * 验证：triangle_area(3,4) → 3*4/2=6 ✅
// 批改总结：✅(1)对 ❌(2)错，product 不多余，是位置错 ⚠️核对原题
// ------------------------------------------------------------

double triangle_area(double base, double height)
{
    double product;
    product = base * height;
    return product / 2;
}

