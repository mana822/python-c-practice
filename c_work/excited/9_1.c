// * 验证原版：2023-3-1 正确是第60天，原版算成91 ❌
// 批改总结：❌2月当30天 ❌循环多算一月 ❌闰年漏year%400 ⚠️见修正版
// ? 只累加 1~month-1 月再加 day；闰年只在 month>2 时补那天。
// ------------------------------------------------------------
int day_of_year(int month, int day, int year)
{
    static int month_days[13] = {
        0, 31, 28, 31, 30, 31, 30,
        31, 31, 30, 31, 30, 31
    };
    int i, sum = day;
    for (i = 1; i < month; i++)
        sum += month_days[i];
    if (month > 2 &&       // 要大于2才行，就是2月我们直接算天就行了
        (year % 4 == 0 && year % 100 != 0 || year % 400 == 0))
        sum++;
    return sum;
}
