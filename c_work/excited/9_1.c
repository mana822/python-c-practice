// 第9章 第5题：num_digits(n)
// ============================================================
// * 你的代码：int i=0; while(n!=0){n/=10;i++;} return i;
// ✅ 完全正确，反复除10数次数，符合提示。
// ⚠️ 题目限定正整数没问题；若 n 可能为 0，0 有 1 位，改用 do-while 更严谨。
// ? while(n!=0) 对负整数也成立（C 的 / 向零取整）。
// * 验证：829→82→8→0，3 次 ✅
// 批改总结：✅全对 ⚠️兼容n=0可用do-while
// ------------------------------------------------------------
int num_digits(int n)
{
    int i = 0;
    do {              // ⚠️ do-while 版，兼容 n=0
        n /= 10;
        i++;
    } while (n != 0);
    return i;
}

// ============================================================
// 第9章 第6题：digit(n, k)
// ============================================================
// * 你的代码：while(k!=0){if(n==0)return 0; a=n%10; n/=10; k--;} return a;
// ✅ 完全正确。%10 取最低位、/10 去掉、k 递减，n变0返回0。
// ⚠️ if(n==0)return 0 放循环开头是关键，放后面会返回最后一次的 a。
// * 验证：digit(829,1)=9 ✅ (829,2)=2 ✅ (829,3)=8 ✅ (829,4)=0 ✅
// 批改总结：✅全对 ⚠️注意 if(n==0) 的位置
// ------------------------------------------------------------
int digit(int n, int k)
{
    int a;
    while (k != 0) {
        if (n == 0) return 0;
        a = n % 10;
        n /= 10;
        k--;
    }
    return a;
}

