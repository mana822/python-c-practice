// 声明 int fib_number[40]，填入前 40 个斐波那契数。
// ------------------------------------------------------------

// * 你的代码：
#include <stdio.h>

int main(void)
{
    int fib_number[40] = {0, 1};   // * 前两个数 0、1，其余自动为 0。

    // ✅ 从下标 2 开始填到下标 39，共 38 个数。
    // * fib_number[i+2] = fib_number[i] + fib_number[i+1] 正确。
    for (int i = 0; i < 38; i++)
        fib_number[i + 2] = fib_number[i] + fib_number[i + 1];

    // ✅ 输出 40 个数，正确。
    // ? 建议每个数后面加一个空格，最后一个可换行，便于查看。
    for (int i = 0; i < 40; i++) {
        printf("%d ", fib_number[i]);
    }
    printf("\n");

    return 0;
}

// * 批改：✅ 完全正确。
//   - 数组长度 40，初始化前两个为 0、1，正确。
