// C99 重复第3题，但用指示器，初始化器尽可能简短。
// ------------------------------------------------------------

// * 你的原答：
// 4.答: bool weekend[] = {true, weekend[6] = true};

// ! 批改：❌ 语法错误。
// * 指示器（designated initializer）的写法是 [下标] = 值，
//   不是数组名[下标] = 值。
//   你写的 weekend[6] = true 是赋值表达式，不是指示器，放在初始化器里不合法。
// * 正确写法（简短）：
//     bool weekend[7] = {[0] = true, [6] = true};
//   或者省略长度：
//     bool weekend[] = {[0] = true, [6] = true};
//   因为指定了最大下标 6，数组长度自动确定为 7。
// * 【C23 变化】C23 仍然支持指定初始化器，语法与 C99 相同；
//   bool/true/false 在 C23 中是关键字，无需 <stdbool.h>。
// * 正确答案：
//     bool weekend[] = {[0] = true, [6] = true};
//   或
//     bool weekend[7] = {[0] = true, [6] = true};

