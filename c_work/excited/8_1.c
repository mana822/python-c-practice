// * 第1题：
// 表达式 sizeof(a) / sizeof(t) 也能算元素个数，为什么较差？
// ------------------------------------------------------------

// * 你的原答：
// 1.答: 如果改了类型，t 要跟着变

// * 批改：✅ 基本正确，但不够完整。
// * 更完整的理由：
//   1. 数组元素类型改变时，t 必须同步修改，否则比例算错；
//      sizeof(a) / sizeof(a[0]) 会自动适应元素类型，不会漏改。
//   2. 如果 a 不是数组而是指针，sizeof(a) / sizeof(t) 会得到
//      “指针大小 / 元素大小”，结果没有意义；
//      sizeof(a) / sizeof(a[0]) 对指针同样不对，但至少写法统一。
//   3. sizeof(a) / sizeof(a[0]) 不依赖手写类型名，
//      不容易因为复制粘贴、改类型而引入错误。
// * 正确答案：因为 t 是手写的类型名，数组元素类型一旦改变，
//   t 必须同步修改，否则会算错；而 sizeof(a[0]) 自动跟随元素类型，
//   更安全、更不容易出错。

