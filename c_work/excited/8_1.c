// * 第2题：
// 如何使用（字符格式的）数字作为数组下标？
// ------------------------------------------------------------

// * 你的原答：
// 2.答: 都先减一个 '1'。

// ! 批改：❌ 错误。应该减 '0'，不是 '1'。
// * 字符 '0' 的 ASCII 码是 48，'1' 是 49，……，'9' 是 57。
//   要把字符数字转换成 0~9 的整数下标，应减去 '0'：
//     int index = ch - '0';
//   例如：
//     '0' - '0' = 0
//     '3' - '0' = 3
//     '9' - '0' = 9
//   如果减 '1'：
//     '0' - '1' = -1
//     '3' - '1' = 2
//   下标会整体偏移，结果错误。
// * 正确示例：
//     int count[10] = {0};
//     char ch;
//     while ((ch = getchar()) >= '0' && ch <= '9')
//         count[ch - '0']++;
// * 正确答案：用字符减去 '0' 得到 0~9 的下标，例如 count[ch - '0']。

